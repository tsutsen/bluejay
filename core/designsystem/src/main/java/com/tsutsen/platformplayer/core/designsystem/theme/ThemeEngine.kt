package com.tsutsen.platformplayer.core.designsystem.theme

import androidx.compose.material3.ColorScheme
import androidx.compose.ui.graphics.Color
import com.google.android.material.color.utilities.DynamicScheme
import com.google.android.material.color.utilities.Hct
import com.google.android.material.color.utilities.MathUtils
import com.google.android.material.color.utilities.TonalPalette
import com.google.android.material.color.utilities.Variant
import com.tsutsen.platformplayer.core.datastore.model.PaletteStyle

/**
 * Theme engine — turns a few key colors into a full Material 3 theme pair.
 *
 * The user supplies [primary], and optionally [secondary]/[tertiary]; every
 * other role (40 of them, light and dark) is generated by the same
 * material-color-utilities pipeline PixelPlayer uses, so a custom theme is
 * as complete as a Material You one.
 *
 * Uses the API bundled in com.google.android.material:material (the app
 * already depends on it). Pure and allocation-cheap — results can be
 * remembered keyed by the inputs.
 */
object ThemeEngine {
    data class Schemes(
        val light: ColorScheme,
        val dark: ColorScheme,
    )

    /**
     * @param primary key color, ARGB (0xAARRGGBB)
     * @param secondary key color, ARGB, or null to derive from primary
     * @param tertiary key color, ARGB, or null to derive from secondary/primary
     * @param background optional surface color, ARGB — when set, the neutral
     *        palettes (surfaces, backgrounds) take its hue at low chroma
     *        instead of being derived from [primary], so themes are not
     *        locked to white/dark.
     * @param contrast contrast refinement, -1 (minimum) to 1 (maximum),
     *        0 = standard. Drives the per-role ContrastCurves in the spec.
     */
    fun generate(
        primary: Int,
        secondary: Int?,
        tertiary: Int?,
        style: PaletteStyle,
        background: Int? = null,
        contrast: Float = 0f,
    ): Schemes {
        val palettes = buildPalettes(primary, secondary, tertiary, style, background)
        // Trust boundary: this also reads persisted user data.
        val level = contrast.toDouble().coerceIn(-1.0, 1.0)
        val source = Hct.fromInt(primary)

        // Verified against the material 1.13.0-bundled DynamicScheme: with
        // explicit palettes the variant is only stored, never read for role
        // tones (only FIDELITY/CONTENT/MONOCHROME variants alter tones), so
        // the style's behavior lives in [buildPalettes], not here.
        val variant = variantFor(style)
        return Schemes(
            light =
                DynamicScheme(
                    source,
                    variant,
                    false,
                    level,
                    palettes.primary,
                    palettes.secondary,
                    palettes.tertiary,
                    palettes.neutral,
                    palettes.neutralVariant,
                ).toComposeColorScheme(),
            dark =
                DynamicScheme(
                    source,
                    variant,
                    true,
                    level,
                    palettes.primary,
                    palettes.secondary,
                    palettes.tertiary,
                    palettes.neutral,
                    palettes.neutralVariant,
                ).toComposeColorScheme(),
        )
    }

    // Hue rotation tables from the material-color-utilities spec as bundled
    // in material 1.13.0 (SchemeVibrant / SchemeExpressive).
    private val VIBRANT_HUES =
        doubleArrayOf(0.0, 41.0, 61.0, 101.0, 131.0, 181.0, 251.0, 301.0, 360.0)
    private val VIBRANT_SECONDARY_ROTATIONS =
        doubleArrayOf(18.0, 15.0, 10.0, 12.0, 15.0, 18.0, 15.0, 12.0, 12.0)
    private val VIBRANT_TERTIARY_ROTATIONS =
        doubleArrayOf(35.0, 30.0, 20.0, 25.0, 30.0, 35.0, 30.0, 25.0, 25.0)
    private val EXPRESSIVE_HUES =
        doubleArrayOf(0.0, 21.0, 51.0, 121.0, 151.0, 191.0, 271.0, 321.0, 360.0)
    private val EXPRESSIVE_SECONDARY_ROTATIONS =
        doubleArrayOf(45.0, 95.0, 45.0, 20.0, 45.0, 90.0, 45.0, 45.0, 45.0)
    private val EXPRESSIVE_TERTIARY_ROTATIONS =
        doubleArrayOf(120.0, 120.0, 20.0, 45.0, 20.0, 15.0, 20.0, 120.0, 120.0)

    /**
     * Per-style tonal palette construction.
     *
     * The user's picked colors are always respected verbatim ([TonalPalette.
     * fromInt]); the style only decides how the *unpicked* palettes
     * (secondary, tertiary, neutral, neutralVariant) are derived from the
     * primary. Hues and chromas follow the material-color-utilities spec as
     * bundled in material 1.13.0 (SchemeTonalSpot/Vibrant/Expressive/
     * FruitSalad), so each style keeps its spec hue character (analogous,
     * rotated, +15° neutrals, −50° salad) and the four read as distinct
     * palettes.
     */
    private data class Palettes(
        val primary: TonalPalette,
        val secondary: TonalPalette,
        val tertiary: TonalPalette,
        val neutral: TonalPalette,
        val neutralVariant: TonalPalette,
    )

    private fun buildPalettes(
        primary: Int,
        secondary: Int?,
        tertiary: Int?,
        style: PaletteStyle,
        background: Int? = null,
    ): Palettes {
        val source = Hct.fromInt(primary)
        val hue = source.hue
        val picked = { argb: Int? -> argb?.let { TonalPalette.fromInt(it) } }

        // Chroma ladder is deliberately spread (16..56) so the four styles read
        // as distinct in the picker swatches while staying within pleasing
        // territory (chroma <= ~56). Hues still follow the spec rotation tables.
        val secondaryTonal =
            when (style) {
                PaletteStyle.TONAL_SPOT -> TonalPalette.fromHueAndChroma(hue, 16.0)
                PaletteStyle.VIBRANT ->
                    TonalPalette.fromHueAndChroma(
                        DynamicScheme.getRotatedHue(source, VIBRANT_HUES, VIBRANT_SECONDARY_ROTATIONS),
                        56.0,
                    )
                PaletteStyle.EXPRESSIVE ->
                    TonalPalette.fromHueAndChroma(
                        DynamicScheme.getRotatedHue(
                            source,
                            EXPRESSIVE_HUES,
                            EXPRESSIVE_SECONDARY_ROTATIONS,
                        ),
                        36.0,
                    )
                PaletteStyle.FRUIT_SALAD ->
                    TonalPalette.fromHueAndChroma(MathUtils.sanitizeDegreesDouble(hue - 60.0), 48.0)
            }

        val tertiaryTonal =
            when (style) {
                PaletteStyle.TONAL_SPOT ->
                    TonalPalette.fromHueAndChroma(MathUtils.sanitizeDegreesDouble(hue + 60.0), 24.0)
                PaletteStyle.VIBRANT ->
                    TonalPalette.fromHueAndChroma(
                        DynamicScheme.getRotatedHue(source, VIBRANT_HUES, VIBRANT_TERTIARY_ROTATIONS),
                        48.0,
                    )
                PaletteStyle.EXPRESSIVE ->
                    TonalPalette.fromHueAndChroma(
                        DynamicScheme.getRotatedHue(
                            source,
                            EXPRESSIVE_HUES,
                            EXPRESSIVE_TERTIARY_ROTATIONS,
                        ),
                        40.0,
                    )
                PaletteStyle.FRUIT_SALAD ->
                    TonalPalette.fromHueAndChroma(MathUtils.sanitizeDegreesDouble(hue - 120.0), 44.0)
            }

        val neutralChroma: Double
        val neutralVariantChroma: Double
        val neutralHueShift: Double
        when (style) {
            PaletteStyle.TONAL_SPOT -> {
                neutralChroma = 6.0; neutralVariantChroma = 8.0; neutralHueShift = 0.0
            }
            PaletteStyle.VIBRANT -> {
                neutralChroma = 12.0; neutralVariantChroma = 16.0; neutralHueShift = 0.0
            }
            PaletteStyle.EXPRESSIVE -> {
                neutralChroma = 8.0; neutralVariantChroma = 12.0; neutralHueShift = 15.0
            }
            PaletteStyle.FRUIT_SALAD -> {
                neutralChroma = 14.0; neutralVariantChroma = 20.0; neutralHueShift = 10.0
            }
        }
        // A user-picked background owns the neutral hue (both light and dark
        // surfaces keep its hue) but surfaces stay near-neutral: the palettes
        // are rebuilt at the style's low spec chroma instead of taking the
        // background's full chroma, and neutral/neutralVariant stay distinct.
        val neutralHue =
            background?.let { MathUtils.sanitizeDegreesDouble(Hct.fromInt(it).hue) }
                ?: MathUtils.sanitizeDegreesDouble(hue + neutralHueShift)

        return Palettes(
            primary = TonalPalette.fromInt(primary),
            secondary = picked(secondary) ?: secondaryTonal,
            tertiary = picked(tertiary) ?: tertiaryTonal,
            neutral = TonalPalette.fromHueAndChroma(neutralHue, neutralChroma),
            neutralVariant = TonalPalette.fromHueAndChroma(neutralHue, neutralVariantChroma),
        )
    }

    private fun variantFor(style: PaletteStyle): Variant =
        when (style) {
            PaletteStyle.TONAL_SPOT -> Variant.TONAL_SPOT
            PaletteStyle.VIBRANT -> Variant.VIBRANT
            PaletteStyle.EXPRESSIVE -> Variant.EXPRESSIVE
            PaletteStyle.FRUIT_SALAD -> Variant.FRUIT_SALAD
        }
}

private fun DynamicScheme.toComposeColorScheme(): ColorScheme =
    ColorScheme(
        primary = Color(getPrimary()),
        onPrimary = Color(getOnPrimary()),
        primaryContainer = Color(getPrimaryContainer()),
        onPrimaryContainer = Color(getOnPrimaryContainer()),
        inversePrimary = Color(getInversePrimary()),
        secondary = Color(getSecondary()),
        onSecondary = Color(getOnSecondary()),
        secondaryContainer = Color(getSecondaryContainer()),
        onSecondaryContainer = Color(getOnSecondaryContainer()),
        tertiary = Color(getTertiary()),
        onTertiary = Color(getOnTertiary()),
        tertiaryContainer = Color(getTertiaryContainer()),
        onTertiaryContainer = Color(getOnTertiaryContainer()),
        background = Color(getBackground()),
        onBackground = Color(getOnBackground()),
        surface = Color(getSurface()),
        onSurface = Color(getOnSurface()),
        surfaceVariant = Color(getSurfaceVariant()),
        onSurfaceVariant = Color(getOnSurfaceVariant()),
        surfaceTint = Color(getSurfaceTint()),
        inverseSurface = Color(getInverseSurface()),
        inverseOnSurface = Color(getInverseOnSurface()),
        error = Color(getError()),
        onError = Color(getOnError()),
        errorContainer = Color(getErrorContainer()),
        onErrorContainer = Color(getOnErrorContainer()),
        outline = Color(getOutline()),
        outlineVariant = Color(getOutlineVariant()),
        scrim = Color(getScrim()),
        surfaceBright = Color(getSurfaceBright()),
        surfaceDim = Color(getSurfaceDim()),
        surfaceContainer = Color(getSurfaceContainer()),
        surfaceContainerHigh = Color(getSurfaceContainerHigh()),
        surfaceContainerHighest = Color(getSurfaceContainerHighest()),
        surfaceContainerLow = Color(getSurfaceContainerLow()),
        surfaceContainerLowest = Color(getSurfaceContainerLowest()),
        primaryFixed = Color(getPrimaryFixed()),
        primaryFixedDim = Color(getPrimaryFixedDim()),
        onPrimaryFixed = Color(getOnPrimaryFixed()),
        onPrimaryFixedVariant = Color(getOnPrimaryFixedVariant()),
        secondaryFixed = Color(getSecondaryFixed()),
        secondaryFixedDim = Color(getSecondaryFixedDim()),
        onSecondaryFixed = Color(getOnSecondaryFixed()),
        onSecondaryFixedVariant = Color(getOnSecondaryFixedVariant()),
        tertiaryFixed = Color(getTertiaryFixed()),
        tertiaryFixedDim = Color(getTertiaryFixedDim()),
        onTertiaryFixed = Color(getOnTertiaryFixed()),
        onTertiaryFixedVariant = Color(getOnTertiaryFixedVariant()),
    )
