package com.futo.platformplayer.views.fields

/**
 * Stub annotation for advanced settings fields.
 * This annotation was used by the deleted XML-based settings UI to mark
 * fields as advanced (hidden by default). It is retained here as a no-op
 * annotation to avoid breaking compilation in Settings.kt.
 */
@Retention(AnnotationRetention.BINARY)
@Target(AnnotationTarget.FIELD)
annotation class AdvancedField
