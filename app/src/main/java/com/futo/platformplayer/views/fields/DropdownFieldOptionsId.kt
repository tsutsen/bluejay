package com.futo.platformplayer.views.fields

/**
 * Stub annotation for dropdown field options.
 * This annotation was used by the deleted XML-based DropdownField to populate
 * dropdown menus with options from XML arrays. It is retained here as a no-op
 * annotation to avoid breaking compilation in Settings.kt.
 */
@Retention(AnnotationRetention.BINARY)
@Target(AnnotationTarget.FIELD)
annotation class DropdownFieldOptionsId(val value: Int)
